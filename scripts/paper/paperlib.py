"""Shared helpers for the paper's generated values, tables and figures (scripts/paper/build.py).

Every number the paper prints comes from a file that git tracks and that has no uncommitted change: `Sources.path`
refuses anything else and records the file's blob hash, so each artifact can list exactly what it was built from.
Values are formatted here once (siunitx), so the .tex sources contain no hand-typed numbers.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "paper" / "generated"


def _git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout.strip()


class Sources:
    """Per artifact, the committed files it reads, with their blob hashes."""

    def __init__(self):
        self.by_artifact: dict[str, dict[str, str]] = {}

    def path(self, artifact: str, rel: str) -> Path:
        tracked = subprocess.run(["git", "ls-files", "--error-unmatch", rel], cwd=ROOT, capture_output=True)
        if tracked.returncode != 0:
            raise RuntimeError(f"{rel}: not tracked by git; the paper uses committed results only")
        if subprocess.run(["git", "diff", "--quiet", "HEAD", "--", rel], cwd=ROOT).returncode != 0:
            raise RuntimeError(f"{rel}: has uncommitted changes; commit it before building the paper")
        self.by_artifact.setdefault(artifact, {})[rel] = _git("rev-parse", f"HEAD:{rel}")[:12]
        return ROOT / rel

    def json(self, artifact: str, rel: str):
        return json.loads(self.path(artifact, rel).read_text())

    def yaml(self, artifact: str, rel: str):
        return yaml.safe_load(self.path(artifact, rel).read_text())

    def text(self, artifact: str, rel: str) -> str:
        return self.path(artifact, rel).read_text()

    def header(self, artifact: str, script: str) -> str:
        """The comment block every generated .tex file starts with."""
        lines = [f"% GENERATED by {script}; do not edit. Rebuild: uv run python scripts/paper/build.py",
                 f"% artifact: {artifact}", "% sources (path @ git blob):"]
        lines += [f"%   {p} @ {b}" for p, b in sorted(self.by_artifact.get(artifact, {}).items())]
        return "\n".join(lines) + "\n"


# ------------------------------------------------------------------------------------------- formatting (siunitx)
def num(x: float, nd: int = 3, sign: bool = False) -> str:
    """\\num{...} with `nd` decimals; `sign` keeps an explicit + (siunitx retain-explicit-plus)."""
    s = f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    if s.lstrip("+-").strip("0.") == "" and s.startswith("-"):
        s = s[1:]  # no "-0.000"
    return f"\\num{{{s}}}"


def integer(n: int) -> str:
    return f"\\num{{{int(n)}}}"


def pct(x: float, nd: int = 1) -> str:
    """A share (0.683) as a percentage: \\SI{68.3}{\\percent}."""
    return f"\\SI{{{100 * x:.{nd}f}}}{{\\percent}}"


def ci(lo: float, hi: float, nd: int = 3, sign: bool = True) -> str:
    return f"[{num(lo, nd, sign)}, {num(hi, nd, sign)}]"


def est_ci(d: dict, key: str = "ci90", nd: int = 3, sign: bool = True) -> str:
    """'value [lo, hi]' from a statistic dict with `value` and `key`."""
    return f"{num(d['value'], nd, sign)} {ci(*d[key], nd=nd, sign=sign)}"


def pval(p: float) -> str:
    """One-sided bootstrap p: 0 means none of the resamples, so it is reported as below 1/B."""
    return "\\num{<1e-4}" if p == 0 else (f"\\num{{{p:.3f}}}" if p >= 0.001 else f"\\num{{{p:.1e}}}")


UNICODE = {"σ": r"$\sigma$", "μ": r"$\mu$", "κ": r"$\kappa$", "ρ": r"$\rho$", "×": r"$\times$", "≥": r"$\geq$",
           "≤": r"$\leq$", "≡": r"$\equiv$", "≈": r"$\approx$", "∧": r"$\wedge$", "→": r"$\rightarrow$", "±": r"$\pm$",
           "−": r"$-$", "·": r"$\cdot$", "–": "--", "—": "---", "’": "'", "‘": "`", "“": "``", "”": "''", "…": r"\ldots{}",
           "²": r"$^2$", "⁻": r"$^-$", "³": r"$^3$", "′": "'", "√": r"$\surd$", "∈": r"$\in$", "Δ": r"$\Delta$",
           "§": r"\S{}", "∖": r"$\setminus$"}


def tex_escape(s: str) -> str:
    rep = {"&": r"\&", "%": r"\%", "_": r"\_", "#": r"\#", "^": r"\^{}", "*": r"$^{*}$", "$": r"\$", **UNICODE}
    return "".join(rep.get(c, c) for c in s)


def ascii_only(name: str, text: str) -> str:
    """Generated LaTeX must compile under pdflatex (arXiv) as well as tectonic: no raw non-ASCII characters."""
    bad = sorted({c for c in text if ord(c) > 127})
    if bad:
        raise ValueError(f"{name}: non-ASCII characters {bad}; add them to paperlib.UNICODE")
    return text


class Macros:
    """Named values for the prose: \\defpv{key}{value}, used as \\pv{key} (an undefined key is a LaTeX error)."""

    def __init__(self):
        self.values: dict[str, tuple[str, str]] = {}

    def add(self, key: str, value: str, source: str) -> None:
        if key in self.values and self.values[key][0] != value:
            raise ValueError(f"macro {key} defined twice with different values")
        self.values[key] = (value, source)

    def tex(self, header: str) -> str:
        body = [header, "\\makeatletter"]
        body += [f"\\defpv{{{k}}}{{{v}}}% {src}" for k, (v, src) in sorted(self.values.items())]
        return "\n".join(body + ["\\makeatother", ""])
