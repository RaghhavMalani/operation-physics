"""The paper's sources (paper/, scripts/paper/): every generated value the text uses exists, the drafted sections contain
no hand-typed numbers, every generated table and figure names the committed files it was built from, and the
committed generated files are what a fresh build produces. CPU only; no LaTeX needed."""

import json
import re
import subprocess
import sys

import pytest

from physcal.config import REPO_ROOT

PAPER = REPO_ROOT / "paper"
GEN = PAPER / "generated"
DRAFTED = ("setup", "methods", "protocol")  # the sections drafted so far; the others are marked stubs


def _strip_comments(tex: str) -> str:
    return re.sub(r"(?<!\\)%.*", "", tex)


def _pv_keys(tex: str) -> set[str]:
    return set(re.findall(r"\\pv\{([^}]*)\}", _strip_comments(tex)))


def test_every_value_the_text_uses_is_generated():
    defined = set(re.findall(r"\\defpv\{([^}]*)\}", (GEN / "macros.tex").read_text()))
    used = set()
    for f in [PAPER / "main.tex", *(PAPER / "sections").glob("*.tex")]:
        used |= _pv_keys(f.read_text())
    assert used and used <= defined, sorted(used - defined)


def hand_typed_numbers(tex: str) -> list[str]:
    """Numbers typed into prose: outside comments, generated values, cross-references and identifiers (A6c, K1, R4-5,
    D-pos-v2, bf16). In math, single-digit constants (2\\Phi(z) - 1) are allowed; anything longer is not."""
    t = _strip_comments(tex)
    t = re.sub(r"\\(pv|ref|eqref|label|cite|citep|citet|input|includegraphics|path|texttt)(\[[^\]]*\])?\{[^}]*\}", " ", t)
    found = []
    maths = re.findall(r"\$[^$]*\$|\\begin\{equation\}.*?\\end\{equation\}", t, flags=re.S)
    for m in maths:
        found += [x for x in re.findall(r"(?<![A-Za-z\\])\d+(?:\.\d+)?", m) if len(x) > 1]
    prose = re.sub(r"\$[^$]*\$|\\begin\{equation\}.*?\\end\{equation\}", " ", t, flags=re.S)
    found += re.findall(r"(?<![A-Za-z\d\-\\_])\d+(?:[.,]\d+)?(?![A-Za-z\d])", prose)
    return found


@pytest.mark.parametrize("name", DRAFTED)
def test_drafted_sections_have_no_hand_typed_numbers(name):
    assert hand_typed_numbers((PAPER / "sections" / f"{name}.tex").read_text()) == []


def test_the_number_check_catches_numbers_and_spares_identifiers():
    assert hand_typed_numbers("the slope is 0.816 on 3 seeds") == ["0.816", "3"]
    assert hand_typed_numbers("$k = 10$ and $\\sigma = 0.5$") == ["10", "0.5"]
    assert hand_typed_numbers("A6c, K1--K8, R4-5, D-pos-v2, bf16, $2\\Phi(z)-1$, \\pv{gate.n} % 42 in a comment") == []


@pytest.mark.parametrize("name", DRAFTED)
def test_drafted_claims_cite_a_finding_or_decision(name):
    """Every paragraph of drafted prose follows a comment that cites a FINDINGS number or a D-entry."""
    paras = re.split(r"\n\s*\n", (PAPER / "sections" / f"{name}.tex").read_text())
    for p in paras:
        prose = _strip_comments(p).strip()
        if not prose or prose.startswith(("\\section", "\\subsection", "\\input", "\\begin{description}", "\\end{")) \
                and len(prose.splitlines()) <= 2:
            continue
        comments = " ".join(re.findall(r"(?<!\\)%(.*)", p))
        assert re.search(r"\bD\d+|FINDINGS|#\d+|R\d-\d|CLAUDE\.md|PREREGISTRATION|configs/|physcal/", comments), p[:200]


def test_every_generated_file_names_its_committed_sources():
    rec = json.loads((GEN / "sources.json").read_text())
    tracked = set(subprocess.run(["git", "ls-files"], cwd=REPO_ROOT, capture_output=True, text=True).stdout.split())
    for art, srcs in rec["artifacts"].items():
        assert srcs, art
        assert set(srcs) <= tracked, (art, set(srcs) - tracked)
    for t in rec["tables"]:
        head = (GEN / "tables" / f"{t}.tex").read_text().split("\\begin", 1)[0]
        assert "% GENERATED by scripts/paper/tables.py" in head and re.search(r"%   \S+ @ [0-9a-f]{12}", head), t
        assert f"table:{t}" in rec["artifacts"]
    assert {"headline.pdf", "headline_data.json"} <= set(rec["figures"]) and rec["artifacts"]["fig_headline"]


def test_generated_tex_is_ascii():
    for f in [GEN / "macros.tex", *(GEN / "tables").glob("*.tex")]:
        assert all(ord(c) < 128 for c in f.read_text()), f.name


def test_the_committed_generated_files_are_a_fresh_build(tmp_path, monkeypatch):
    """Rebuild the values and tables into a scratch directory and compare with paper/generated (figures are built by
    the committed headline script and checked by its own test)."""
    sys.path.insert(0, str(REPO_ROOT / "scripts" / "paper"))
    import macros
    import paperlib
    import tables

    S = paperlib.Sources()
    monkeypatch.setattr(paperlib, "OUT", tmp_path)
    monkeypatch.setattr(tables, "OUT", tmp_path)
    try:
        M = macros.build(S)
        tables.build(S)
    except RuntimeError as exc:  # a source has uncommitted changes: the comparison is meaningless until committed
        pytest.skip(str(exc))
    body = lambda t: "\n".join(ln for ln in t.splitlines() if not ln.startswith("%"))  # values, not blob hashes
    assert body(M.tex(S.header(macros.A, "scripts/paper/macros.py"))) == body((GEN / "macros.tex").read_text())
    for f in (tmp_path / "tables").glob("*.tex"):
        assert body(f.read_text()) == body((GEN / "tables" / f.name).read_text()), f.name
